-- NYSE trading-session calendar. Underpins every point-in-time
-- availability decision in the pipeline.
--
-- This lives in its own `sec_reference` schema, NOT in `sec_silver`,
-- for a specific reason: `sql/02_silver/010_schema.sql` opens with
-- `DROP SCHEMA IF EXISTS sec_silver CASCADE`, and `sub_silver` needs
-- calendar *data* (not just DDL) at build time in order to compute
-- `tradable_from`. A calendar living inside sec_silver would be
-- destroyed by the very rebuild that depends on it.
--
-- Consequently this file is idempotent and is run BEFORE 02_silver by
-- `dera build-silver`. The loader truncates and reloads the rows.
--
-- Populated from data/reference/trading_calendar.csv, generated by
-- `uv run python tools/build_calendar.py` using the NYSE calendar from
-- pandas_market_calendars. The database depends only on this table,
-- never on the library at query time.

CREATE SCHEMA IF NOT EXISTS sec_reference;

CREATE TABLE IF NOT EXISTS sec_reference.trading_calendar (
    session_date   DATE    PRIMARY KEY,
    -- Dense, gap-free, ascending. Makes "N trading sessions later"
    -- integer arithmetic instead of a recursive date walk, which is
    -- what the backtest safety-buffer knob needs.
    session_seq    INTEGER NOT NULL UNIQUE,
    -- The actual closing bell in US Eastern. 16:00 normally, 13:00 on
    -- the ~40 half sessions since 2009 (day after Thanksgiving,
    -- Christmas Eve, some July 3rds). A filing accepted at 14:00 on a
    -- half day is already after the close.
    close_time_et  TIME    NOT NULL,
    -- The same closing bell as an absolute instant. This is what the
    -- availability lookup actually compares against: "the first session
    -- whose bell rings after this filing landed" is then a single
    -- indexed range scan, and daylight-saving transitions are handled
    -- by the stored offset rather than by query-time arithmetic.
    close_at       TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_cal_close_at
    ON sec_reference.trading_calendar (close_at);

COMMENT ON TABLE sec_reference.trading_calendar IS
    'NYSE sessions. Source of truth for when a filing first becomes '
    'actionable. Regenerate with tools/build_calendar.py.';

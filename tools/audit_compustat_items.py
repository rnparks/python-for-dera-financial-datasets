"""Audit the Compustat-style items against S&P's own balancing identities.

WHY. There is no Compustat here to compare with, but S&P publishes how its
items add up (the Xpressfeed balancing model): current assets are cash and
short-term investments plus receivables plus inventories plus other current
assets, and so on. Items resolved from XBRL by data/reference/
compustat_item_map.csv should satisfy the same identities; where they do not,
a mapping is missing a component or taking the wrong one.

WHAT IT REPORTS, on the first vintage of each fiscal year of operating
companies (SIC not 6xxx, total assets over $10M, positive sales), into
docs/audits/compustat_items.md:
  - coverage of every exported item;
  - for each identity, the share of firm-years where both sides are present
    and agree within 1% of total assets, first with every component required,
    then with a missing component taken as zero (Compustat records an absent
    line as zero, XBRL simply has no fact);
  - the largest residuals, so a failure can be traced to a filing.

Read-only. Run after tools/export_compustat.py:
    uv run python tools/audit_compustat_items.py
"""
from __future__ import annotations

import datetime as dt
import sys
from pathlib import Path

import polars as pl

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from dera_pipeline import compustat, config  # noqa: E402

PANEL = config.PROJECT_ROOT / "data" / "exports" / "compustat" / "annual.parquet"
OUT = config.PROJECT_ROOT / "docs" / "audits" / "compustat_items.md"
TOL = 0.01
# S&P Xpressfeed balancing model identities (annual balance sheet and income statement)
IDENTITIES = [
    ("at", ["lt", "seq", "mib"], "AT = LT + SEQ + MIB (temporary equity outside both sides)"),
    ("at", ["lt", "seq", "mib", "_tempeq"], "AT = LT + SEQ + MIB + temporary equity"),
    ("che", ["ivst"], "CHE >= IVST (cash is the remainder)"),
]
# Items defined as S&P remainders (ACO of ACT, LCO of LCT, LO of LT, AO of AT): the sum
# identities hold by construction, so the test is that the remainder is not negative,
# which it is when a component is double counted or mapped to too broad a line.
REMAINDERS = [("aco", "ACT - CHE - RECT - INVT"), ("lco", "LCT - AP - DLC - TXP"),
              ("lo", "LT - LCT - DLTT - TXDITC"), ("ao", "AT - ACT - PPENT - IVAEQ - IVAO - INTAN")]


def main() -> int:
    items = compustat.load_map()
    out_items = compustat.exported(items)
    p = pl.read_parquet(PANEL).sort("avail").unique(["cik", "datadate"], keep="first")
    op = p.filter(((pl.col("sic") < 6000) | (pl.col("sic") >= 7000) | pl.col("sic").is_null())
                  & (pl.col("at") > 10) & (pl.col("sale") > 0))
    lines = [f"# Compustat-style item audit, {dt.date.today().isoformat()}", "",
             "Generated by `tools/audit_compustat_items.py`; do not edit by hand.", "",
             f"Operating companies (SIC not 6xxx, total assets > $10M, positive sales), first vintage of each "
             f"fiscal year: {op.height:,} firm-years, {op['cik'].n_unique():,} companies.", "",
             "## Coverage", "", "| Item | Share of firm-years |", "|---|---:|"]
    cov = op.select([pl.col(c).is_not_null().mean().alias(c) for c in out_items]).row(0, named=True)
    lines += [f"| `{k}` | {v:.1%} |" for k, v in sorted(cov.items(), key=lambda kv: -kv[1])]

    lines += ["", "## S&P balancing identities", "",
              "| Identity | Strict: n | Strict: within 1% of AT | Zero-filled: n | Zero-filled: within 1% of AT |",
              "|---|---:|---:|---:|---:|"]
    worst = []
    for lhs, parts, label in IDENTITIES:
        if label.startswith("CHE >="):
            d = op.filter(pl.col("che").is_not_null() & pl.col("ivst").is_not_null())
            ok = (d["che"] >= d["ivst"] - TOL * d["at"]).mean()
            lines.append(f"| {label} | {d.height:,} | {ok:.1%} | | |")
            continue
        strict = op.filter(pl.all_horizontal([pl.col(c).is_not_null() for c in [lhs] + parts]))
        rhs = pl.sum_horizontal([pl.col(c) for c in parts])
        s_ok = ((strict[lhs] - strict.select(rhs).to_series()).abs() <= TOL * strict["at"]).mean() if strict.height else float("nan")
        zf = op.filter(pl.col(lhs).is_not_null() & pl.any_horizontal([pl.col(c).is_not_null() for c in parts]))
        zrhs = pl.sum_horizontal([pl.col(c).fill_null(0) for c in parts])
        zres = zf.with_columns(resid=(pl.col(lhs) - zrhs))
        z_ok = (zres["resid"].abs() <= TOL * zres["at"]).mean() if zres.height else float("nan")
        lines.append(f"| {label} | {strict.height:,} | {s_ok:.1%} | {zf.height:,} | {z_ok:.1%} |")
        top = zres.with_columns(rel=pl.col("resid").abs() / pl.col("at")).sort("rel", descending=True).head(3)
        for r in top.iter_rows(named=True):
            worst.append(f"- {label}: cik {r['cik']}, {r['datadate']}, {lhs} {r[lhs]:,.1f} vs parts "
                         f"{r[lhs] - r['resid']:,.1f} (residual {r['rel']:.0%} of assets)")
    lines += ["", "## Remainder items", "", "| Item | Defined as | n | Not negative (within 1% of AT) | Median share of AT |",
              "|---|---|---:|---:|---:|"]
    for item, label in REMAINDERS:
        d = op.filter(pl.col(item).is_not_null())
        nonneg = (d[item] >= -TOL * d["at"]).mean() if d.height else float("nan")
        med = (d[item] / d["at"]).median() if d.height else float("nan")
        lines.append(f"| `{item}` | {label} | {d.height:,} | {nonneg:.1%} | {med:.1%} |")
        neg = d.with_columns(rel=pl.col(item) / pl.col("at")).sort("rel").head(3)
        for r in neg.iter_rows(named=True):
            if r["rel"] < -TOL:
                worst.append(f"- `{item}` negative: cik {r['cik']}, {r['datadate']}, {r[item]:,.1f} ({r['rel']:.0%} of assets)")
    lines += ["", "Largest residuals and negative remainders:", ""] + worst
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    print("\n".join(lines[6:]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
